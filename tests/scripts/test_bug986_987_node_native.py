"""BUG-986/987：HedgeDoc 构建诊断（CHK-477）的产品修复。

BUG-986：依赖含原生模块（sqlite3 等）时 alpine 镜像缺 python3/make/g++，
node-gyp 构建失败。BUG-987：Yarn berry 在 Node 24 镜像内 fetch 确定性崩溃
（onCancel），berry 项目优先 node:22-alpine（engines 未排除 22 时）。"""

from __future__ import annotations

import json
from pathlib import Path

from local_webpage_access.dockerfile_templates import (
    _NODE_IMAGE,
    _is_yarn_berry_project,
    _node_image_for_engines,
    _node_source_needs_native_toolchain,
)


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


# ---- BUG-986：原生依赖 → node-gyp 工具链 -------------------------------------


def test_native_toolchain_detected_in_yarn_berry_lock(tmp_path: Path) -> None:
    _write(tmp_path / "yarn.lock", '__metadata:\n  version: 8\n"sqlite3@npm:5.1.7":\n')
    assert _node_source_needs_native_toolchain(tmp_path) is True


def test_native_toolchain_detected_in_pnpm_lock(tmp_path: Path) -> None:
    _write(tmp_path / "pnpm-lock.yaml", "packages:\n  /better-sqlite3@11.0.0:\n")
    assert _node_source_needs_native_toolchain(tmp_path) is True


def test_native_toolchain_detected_in_package_lock_and_pkg_json(tmp_path: Path) -> None:
    _write(tmp_path / "package-lock.json", '{"packages": {"node_modules/bcrypt": {}}}')
    assert _node_source_needs_native_toolchain(tmp_path) is True
    (tmp_path / "package-lock.json").unlink()
    _write(tmp_path / "package.json", json.dumps({"dependencies": {"canvas": "^3.0.0"}}))
    assert _node_source_needs_native_toolchain(tmp_path) is True


def test_native_toolchain_negative(tmp_path: Path) -> None:
    _write(tmp_path / "yarn.lock", '"lodash@npm:4.17.21":\n"sqlite3-cli@npm:1.0.0":\n')
    # sqlite3-cli 不是 sqlite3（前缀边界）；lodash 非原生
    _write(tmp_path / "package.json", json.dumps({"dependencies": {"react": "^19.0.0"}}))
    assert _node_source_needs_native_toolchain(tmp_path) is False
    assert _node_source_needs_native_toolchain(None) is False


def test_render_node_adds_native_toolchain_to_apk(tmp_path: Path) -> None:
    """sqlite3 依赖 → apk 层含 python3/make/g++，且 git 检测不受影响。"""
    from local_webpage_access.dockerfile_templates import _render_node
    from tests.scripts.test_dockerfile_templates import _mk_manifest

    _write(tmp_path / "yarn.lock", '__metadata:\n  version: 8\n"sqlite3@npm:5.1.7":\n')
    _write(tmp_path / "package.json", json.dumps({"name": "demo"}))
    manifest = _mk_manifest()
    rendered = _render_node(manifest, 3000, source_dir=tmp_path)
    assert "apk add --no-cache" in rendered
    apk_line = next(line for line in rendered.splitlines() if "apk add" in line)
    for pkg in ("python3", "make", "g++"):
        assert pkg in apk_line


# ---- BUG-987：yarn berry 避开 Node 24 ---------------------------------------


def test_yarn_berry_detection(tmp_path: Path) -> None:
    assert _is_yarn_berry_project(tmp_path) is False
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _is_yarn_berry_project(tmp_path) is True


def test_yarn_berry_lock_metadata_detection(tmp_path: Path) -> None:
    _write(tmp_path / "yarn.lock", "# This file is generated by yarn\n__metadata:\n  version: 8\n")
    assert _is_yarn_berry_project(tmp_path) is True
    _write(tmp_path / "yarn.lock", "# yarn lockfile v1\n\nlodash@^4.17.21:\n")
    assert _is_yarn_berry_project(tmp_path) is False


def test_berry_project_prefers_node22_within_engines(tmp_path: Path) -> None:
    """HedgeDoc 实案：engines >=18 含 24，berry fetch 在 24 必崩 → 22。"""
    _write(tmp_path / "package.json", json.dumps({"engines": {"node": ">=18"}}))
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _node_image_for_engines(tmp_path) == "node:22-alpine"


def test_berry_project_keeps_default_when_engines_excludes_22(tmp_path: Path) -> None:
    _write(tmp_path / "package.json", json.dumps({"engines": {"node": ">=24"}}))
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _node_image_for_engines(tmp_path) == _NODE_IMAGE


def test_non_berry_project_unaffected(tmp_path: Path) -> None:
    _write(tmp_path / "package.json", json.dumps({"engines": {"node": ">=18"}}))
    assert _node_image_for_engines(tmp_path) == _NODE_IMAGE


def test_berry_engines_capped_below_24_still_uses_engines_path(tmp_path: Path) -> None:
    """engines 已排除 24 时沿用 BUG-967 的 engines 选择（同到 22，语义不冲突）。"""
    _write(tmp_path / "package.json", json.dumps({"engines": {"node": "18.0.0 - 20.x.x"}}))
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _node_image_for_engines(tmp_path) == "node:20-alpine"


def test_berry_fallback_respects_engines_upper_bound_in_22(tmp_path: Path) -> None:
    """评审 P2：``>=24 || >=22.0.0 <22.5.0`` 默认镜像满足但 berry 在 24 必崩；
    与 22 线交集有上界 → 钉 node:22.4-alpine，不用可能越界的 moving tag。"""
    _write(
        tmp_path / "package.json",
        json.dumps({"engines": {"node": ">=24 || >=22.0.0 <22.5.0"}}),
    )
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _node_image_for_engines(tmp_path) == "node:22.4-alpine"


def test_berry_fallback_unbounded_22_intersection_uses_moving_tag(tmp_path: Path) -> None:
    """与 22 线交集延伸到线尾（``>=24 || >=22.12.0``）→ moving tag node:22-alpine。"""
    _write(
        tmp_path / "package.json",
        json.dumps({"engines": {"node": ">=24 || >=22.12.0"}}),
    )
    _write(tmp_path / ".yarn" / "releases" / "yarn-4.13.0.cjs", "")
    assert _node_image_for_engines(tmp_path) == "node:22-alpine"


# ---- 评审回归：宽上界不拼不存在的镜像 tag（BUG-995）----------------------------


def test_engines_wide_upper_bound_uses_moving_tag(tmp_path: Path) -> None:
    """``<=22.99.0`` 的上界 22.99 不是真实次版本——不能拼出 Docker Hub 不存在
    的 node:22.99-alpine（拉取 404），回退 moving tag node:22-alpine。"""
    _write(tmp_path / "package.json", json.dumps({"engines": {"node": "<=22.99.0"}}))
    assert _node_image_for_engines(tmp_path) == "node:22-alpine"


# ---- 评审回归：pnpm v5 锁斜杠包键（BUG-996）------------------------------------


def test_native_toolchain_detected_in_pnpm_v5_lock_slash_key(tmp_path: Path) -> None:
    """pnpm v5 锁文件的包键是斜杠分隔（``/sqlite3/5.1.7:``），不匹配 @ 形式——
    旧正则漏检会让原生依赖在 alpine 内缺 python3/make/g++。"""
    _write(tmp_path / "pnpm-lock.yaml", "lockfileVersion: 5.4\npackages:\n  /sqlite3/5.1.7:\n")
    assert _node_source_needs_native_toolchain(tmp_path) is True


# ---- 评审回归：git 依赖探测走 lifecycle 根（BUG-996）---------------------------


def test_render_node_git_dep_in_source_subdir_detected(tmp_path: Path) -> None:
    """sourceSubdir monorepo：git 依赖声明在子目录 package.json 时，apk 层
    同样要补 git——探测须与 native 同口径走 _node_lifecycle_root。"""
    from local_webpage_access.dockerfile_templates import _render_node
    from tests.scripts.test_dockerfile_templates import _mk_manifest

    _write(tmp_path / "package.json", json.dumps({"name": "mono-root"}))
    _write(
        tmp_path / "server" / "package.json",
        json.dumps({"name": "server", "dependencies": {"lib": "github:user/lib#v1"}}),
    )
    manifest = _mk_manifest()
    manifest.sourceSubdir = "server"
    rendered = _render_node(manifest, 3000, source_dir=tmp_path)
    apk_line = next(line for line in rendered.splitlines() if "apk add" in line)
    assert "git" in apk_line
